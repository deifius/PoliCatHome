import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const base = new URL('../', import.meta.url);
const homepage = readFileSync(new URL('polyc/web/index.html', base), 'utf8');
const src = readFileSync(new URL('polyc/web/branching-home.js', base), 'utf8');
const story = readFileSync(new URL('polyc/web/branching-story.mjs', base), 'utf8');
const css = readFileSync(new URL('polyc/web/branching-home.css', base), 'utf8');
const registry = JSON.parse(readFileSync(new URL('polyc/web/featured-cats.json', base), 'utf8'));
assert.ok(homepage.includes('id="branchingHome"'), 'Run python3 scripts/activate-branching-home.py --apply');
assert.ok(homepage.includes('/web/branching-home.css'));
assert.ok(homepage.includes('/web/branching-home.js'));
assert.ok(homepage.includes('id="catnapPanel"') && homepage.includes('id="createPanel"'), 'Original workflows must remain');
assert.ok(homepage.includes('id="contribute"'), 'Original consent form must remain');
assert.match(src, /validateFeaturedCatalog\(await response\.json\(\)\)/);
assert.match(story, /cat\.repoUrl/);
assert.match(src, /sessionStorage\.getItem\('polyc\.catnap\.node\.v1'\)/);
assert.match(src, /polyc\.home\.start\.v1/);
assert.match(src, /localStorage\.setItem\(PREFERENCE_KEY, PREFERENCE_WORKSPACE\)/);
assert.match(src, /localStorage\.removeItem\(PREFERENCE_KEY\)/);
assert.match(src, /enter-catnap/);
assert.match(src, /enter-create/);
assert.doesNotMatch(src + story, /\/api\/(?:lease|enroll|catnap\/enroll|tasks\/)/, 'The invitation must never invoke compute APIs');
assert.match(css, /height:100dvh/);
assert.match(css, /prefers-reduced-motion/);
assert.match(css, /branching-active \.app-shell/);
assert.ok(registry.cats.length > 0);
const output = execFileSync('python3', ['scripts/activate-branching-home.py', '--check'], { cwd: new URL('..', import.meta.url), encoding: 'utf8' });
assert.match(output, /already active/);
execFileSync('node', ['scripts/test-branching-story.mjs'], { cwd: new URL('..', import.meta.url), stdio: 'inherit' });
console.log('Bloom v4: installation, preference, boundaries, registry, and narrative validated.');
